import { z } from 'zod';
import type {
  AgeGroup,
  AqiCategory,
  CommuteMode,
  CookingFuel,
  HomeType,
  HourlyReading,
  SealingClass,
  SensitivityLevel,
} from '../domain/contracts';
import type { Result } from '../shared/result';

/** Supported multilingual advisory response languages. */
export type Language = 'en' | 'hi';

/** Error codes for AI inference, safety validation, and network operations. */
export type AiErrorCode =
  | 'invalidKey'
  | 'network'
  | 'timeout'
  | 'http'
  | 'rateLimited'
  | 'schema'
  | 'injection'
  | 'groundingViolation'
  | 'consentMissing'
  | 'aborted';

/** Structured AI layer error containing no API keys or allowlisted data payloads. */
export interface AiError {
  readonly code: AiErrorCode;
  readonly message: string;
}

/** Error codes for atmospheric air data retrieval. */
export type AirDataErrorCode =
  'network' | 'timeout' | 'http' | 'schema' | 'invalidCity' | 'aborted';

/** Structured error for ambient air quality data provider operations. */
export interface AirDataError {
  readonly code: AirDataErrorCode;
  readonly message: string;
}

/** Single verified factual claim derived strictly from domain engine computations. */
export interface GroundingFact {
  readonly id: string;
  readonly kind: 'aqi' | 'window' | 'action' | 'assumption' | 'source';
  readonly text: string;
  readonly value?: number;
  readonly unit?: string;
}

/** Household budget categorization band for privacy-preserving AI context. */
export type BudgetBand = 'low' | 'medium' | 'high';

/** Allowlisted, anonymized contextual payload forwarded to AI providers. */
export interface LlmSafeContext {
  readonly city: string;
  readonly aqiCategory: AqiCategory;
  readonly aqiValue: number;
  readonly sensitivityLevel: SensitivityLevel;
  readonly ageGroupsPresent: readonly AgeGroup[];
  readonly homeType: HomeType;
  readonly sealing: SealingClass;
  readonly cookingFuel: CookingFuel;
  readonly commuteMode: CommuteMode;
  readonly budgetBand: BudgetBand;
  readonly language: Language;
  readonly facts: readonly GroundingFact[];
  readonly question: string | null;
}

/** Schema validating structured plan narrative responses from AI providers. */
export const aiPlanNarrativeSchema = z.object({
  summary: z.string().max(400),
  highlights: z
    .array(
      z.object({
        actionId: z.string(),
        reason: z.string().max(200),
      })
    )
    .max(5),
  caution: z.string().max(200),
});

/** Structured narrative plan generated by an AI provider. */
export type AiPlanNarrative = z.infer<typeof aiPlanNarrativeSchema>;

/** Schema validating question-answering responses from AI providers. */
export const aiAnswerSchema = z.object({
  answer: z.string().max(600),
  usedActionIds: z.array(z.string()).max(5),
  refusal: z.boolean(),
});

/** Structured question answer generated by an AI provider. */
export type AiAnswer = z.infer<typeof aiAnswerSchema>;

/** Generic interface implemented by local and cloud AI explanation providers. */
export interface AiProvider {
  readonly id: 'local' | 'gemini';
  /** Synthesizes an explanatory narrative for a daily smog plan. */
  explainPlan(
    ctx: LlmSafeContext,
    signal?: AbortSignal
  ): Promise<Result<AiPlanNarrative, AiError>>;
  /** Answers user questions grounded strictly in supplied domain facts. */
  answer(
    ctx: LlmSafeContext,
    signal?: AbortSignal
  ): Promise<Result<AiAnswer, AiError>>;
}

/** 24-hour diurnal air quality time-series dataset. */
export interface HourlySeries {
  readonly city: string;
  readonly readings: readonly HourlyReading[];
  readonly isSample: boolean;
  readonly attribution?: string;
}

/** Provider interface for fetching ambient diurnal particulate concentrations. */
export interface AirDataProvider {
  readonly id: 'open-meteo' | 'manual' | 'sample';
  /** Retrieves 24-hour diurnal air quality series for a designated city. */
  fetchHourly(
    city: string,
    signal?: AbortSignal
  ): Promise<Result<HourlySeries, AirDataError>>;
}
